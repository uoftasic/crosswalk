// =============================================================================
// CrossWalk 8-bit SAR ADC, successive-approximation register
//
// Synchronous version of the two-row SAR register:
//   mask[N-1:0] : "top row"    one-hot pointer to the bit under test
//   data[N-1:0] : "bottom row" decided bits + trial 1; drives trial[N-1:0]
//   eoc         : the "spare" top-row flop; high for one cycle after the
//                 last decision (i.e. during P9), when data is final
//
// Every flop uses the same clock. Nothing derived from mask or data is ever
// used as a clock, set or reset.
//
// Frame (one conversion = 10 bit-clock periods, see interface doc):
//   P0      load = 1   -> this is the setup period; at the edge ending P0: mask = data = 1000_0000
//   P1..P8  load = 0   -> each edge decides one bit, MSB first
//   P9      eoc  = 1   -> data holds the final code; output register captures
//
// Conventions (interface doc v0.1):
//   comp = 1 means Vsh > Vdac  -> keep the bit under test
//   trial[N-1] is the MSB
// =============================================================================

`default_nettype none //catches wires named incorrectly

module sar_logic #(
    parameter N = 8
) (
    input  wire         clk,        // bit clock 4mhz
    input  wire         rst_n,      // from clockgen block
    input  wire         load,       // start of conversion, high during P0 (synchronous, generated by clock)
    input  wire         comp,       // comparator decision for the bit under test
    output wire [N-1:0] trial,      // trial code to the CDAC
    output wire [N-1:0] final_code, // valid while eoc = 1 (last FF)
    output wire         busy,       // high while a decision is in progress (P1..P8)
    output reg          eoc         // end of conversion: one-cycle pulse in P9 --> enable for output reg
);

    reg  [N-1:0] mask;  // top row 8-bit regster. Holds 8'b10000000 at first, then the 1 gets shifted right every clock cycle
    reg  [N-1:0] data;  // bottom row --> this is the actual data being parsed to the CDAC
0.
    // For bit i: mask[i]   = "this bit is being decided"
    //            mask[i+1] = "the bit above is being decided, so this bit is the next trial"

    wire [N-1:0] mask_above = mask >> 1;            // bit i of this vector is mask[i+1]. This decides which bit is the next trial bit (it is another mask)


// this basically decides which bits are being changed via an OR operation. 
// It decides the bit capturing the compare output (i, coming from mask)
// and the bit being turned to 1 for trial (i+1 coming from mask_above)

    wire [N-1:0] en = mask | mask_above; 

// this is the signal actually fed to "data". {N{comp}} just makes an N-bit binary, all bits holding comp. Decides positionally which bit is being changed to comp via OR

    wire [N-1:0] d  = {N{comp}} | mask_above;

    localparam [N-1:0] START = {1'b1, {(N-1){1'b0}}};   // 1000_0000, start value

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            mask <= {N{1'b0}};                // idle: no bit under test
            data <= {N{1'b0}};
            eoc  <= 1'b0;
        end else if (load) begin
            mask <= START;                    // pointer at the MSB
            data <= START;                    // MSB trial = 1
            eoc  <= 1'b0;
        end else begin
            mask <= mask >> 1;                // top row shifts right (0 shifted in)
            data <= (data & ~en) | (d & en);  // per-bit: EN ? D : hold
            eoc  <= mask[0];                  // spare flop: the 1 shifts out of the LSB
        end
    end

    assign trial      = data;
    assign final_code = data;
    assign busy       = |mask;

    // -------------------------------------------------------------------------
    // Built-in checks. Enable with +define+SAR_ASSERTIONS (Verilator: --assert,
    // SV mode). Immediate assertions only, so Verilator and Yosys -formal accept them.
    // -------------------------------------------------------------------------
`ifdef SAR_ASSERTIONS
    always @(posedge clk) begin
        if (rst_n) begin
            // top row is one-hot or zero
            assert ((mask & (mask - 1'b1)) == {N{1'b0}});
            // bits below the bit under test are still 0
            if (|mask) assert ((data & (mask - 1'b1)) == {N{1'b0}});
            // bit under test always holds its trial 1 while being decided
            if (|mask) assert ((data & mask) == mask);
            // eoc only when no decision is in progress
            if (eoc) assert (mask == {N{1'b0}});
        end
    end
`endif

endmodule

`default_nettype wire